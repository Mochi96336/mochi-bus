import { readFile } from 'node:fs/promises'
import { describe, expect, test } from 'vitest'

const workflowUrl = new URL('../../.github/workflows/apply-instance-bundle-pr.yml', import.meta.url)
const runnerUrl = new URL('./apply-bundle-pr-workflow.mjs', import.meta.url)
const runVerifierUrl = new URL('./verify-review-run-workflow.mjs', import.meta.url)
const documentationUrl = new URL('../../docs/INSTANCE_BUNDLE_APPLY_PR_WORKFLOW.md', import.meta.url)

async function source(url) {
  return readFile(url, 'utf8')
}

describe('manual reviewed bundle apply-to-PR workflow contracts', () => {
  test('is manual-only with the exact minimum write permissions', async () => {
    const workflow = await source(workflowUrl)
    expect(workflow).toMatch(/\bon:\n  workflow_dispatch:/)
    expect(workflow).not.toMatch(/^  (push|pull_request|pull_request_target|schedule|issue_comment|workflow_run):/m)
    expect(workflow).toMatch(/permissions:\n  actions: read\n  contents: write\n  pull-requests: write\n/)
    expect(workflow).toContain('Type APPLY')
    expect(workflow).not.toContain('secrets.')
  })

  test('verifies the exact successful review workflow run before downloading its artifact', async () => {
    const workflow = await source(workflowUrl)
    const preflightIndex = workflow.indexOf('node scripts/instance/apply-bundle-pr-workflow.mjs --preflight')
    const fetchRunIndex = workflow.indexOf('name: Fetch exact review workflow run metadata')
    const verifyRunIndex = workflow.indexOf('node scripts/instance/verify-review-run-workflow.mjs')
    const downloadIndex = workflow.indexOf('actions/download-artifact@3e5f45b2cfb9172054b4087a40e8e0b5a5461e7c')
    const applyIndex = workflow.indexOf('node scripts/instance/apply-bundle-pr-workflow.mjs --apply')
    expect(preflightIndex).toBeGreaterThan(-1)
    expect(fetchRunIndex).toBeGreaterThan(preflightIndex)
    expect(verifyRunIndex).toBeGreaterThan(fetchRunIndex)
    expect(downloadIndex).toBeGreaterThan(verifyRunIndex)
    expect(applyIndex).toBeGreaterThan(downloadIndex)
    expect(workflow).toContain('gh api \\')
    expect(workflow).toContain('repos/${GITHUB_REPOSITORY}/actions/runs/${REVIEW_RUN_ID}')
    expect(workflow).toContain('> .generated/apply-review-run.json')
    expect(workflow).toContain('name: ${{ steps.preflight.outputs.artifact_name }}')
    expect(workflow).toContain('run-id: ${{ steps.preflight.outputs.review_run_id }}')
    expect(workflow).toContain('repository: ${{ github.repository }}')
    expect(workflow).toContain('github-token: ${{ github.token }}')
    expect(workflow).toContain('digest-mismatch: error')
    expect(workflow).toContain('path: .generated/apply-input')
  })

  test('persists evidence before committing and creates only a Draft PR', async () => {
    const workflow = await source(workflowUrl)
    const uploadIndex = workflow.indexOf('name: Upload apply evidence')
    const commitIndex = workflow.indexOf('name: Commit only the reviewed manifest')
    const prIndex = workflow.indexOf('gh pr create')
    expect(uploadIndex).toBeGreaterThan(-1)
    expect(commitIndex).toBeGreaterThan(uploadIndex)
    expect(prIndex).toBeGreaterThan(commitIndex)
    expect(workflow).toContain('actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02')
    expect(workflow).toContain('.generated/apply-review-run.json')
    expect(workflow).toContain('if-no-files-found: error')
    expect(workflow).toContain('include-hidden-files: true')
    expect(workflow).toContain('gh pr create \\\n            --draft')
    expect(workflow).not.toMatch(/gh pr (merge|ready)/)
    expect(workflow).not.toMatch(/git push[^\n]*(main|master|integration)/)
  })

  test('requires exactly one reviewed manifest change before push', async () => {
    const workflow = await source(workflowUrl)
    expect(workflow).toContain('test "$(git rev-parse HEAD)" = "${GITHUB_SHA}"')
    expect(workflow).toContain('Expected exactly one non-generated working-tree change')
    expect(workflow).toContain('test "${status}" = " M"')
    expect(workflow).toContain('test "${path}" = "${CONFIG_PATH}"')
    expect(workflow).toContain('git diff --check -- "${CONFIG_PATH}"')
    expect(workflow).toContain('git add -- "${CONFIG_PATH}"')
    expect(workflow).toContain('git diff --cached --name-only --diff-filter=ACMRTUXB')
    expect(workflow).toContain('git switch -c "${APPLY_BRANCH}"')
    expect(workflow).toContain('git push --set-upstream origin "${APPLY_BRANCH}"')
    expect(workflow).not.toContain('git add -A')
    expect(workflow).not.toContain('git add .')
  })

  test('does not install, compile, deploy or contact infrastructure', async () => {
    const workflow = await source(workflowUrl)
    expect(workflow).not.toMatch(/\bnpm\s+(ci|install|run instance:compile|run deploy)\b/)
    expect(workflow).not.toMatch(/\b(wrangler|curl|wget)\b/)
    expect(workflow).not.toContain('CLOUDFLARE_')
    expect(workflow).not.toContain('TDX_CLIENT_')
    expect(workflow).not.toContain('R2_SECRET_')
  })

  test('review-run verifier is local-only and binds workflow, status, attempt and repository', async () => {
    const verifier = await source(runVerifierUrl)
    expect(verifier).not.toMatch(/from\s+['"](?:node:)?child_process['"]|import\(\s*['"](?:node:)?child_process['"]\s*\)|require\(\s*['"](?:node:)?child_process['"]\s*\)/)
    expect(verifier).not.toMatch(/node:https|node:http|undici|\bfetch\s*\(/)
    expect(verifier).toContain("'.github/workflows/review-instance-bundle.yml'")
    expect(verifier).toContain("metadata?.event !== 'workflow_dispatch'")
    expect(verifier).toContain("metadata?.status !== 'completed' || metadata?.conclusion !== 'success'")
    expect(verifier).toContain('review run attempt does not match artifact_name')
    expect(verifier).toContain('metadata?.repository?.full_name !== inputs.repository')
    expect(verifier).toContain('metadata?.head_repository?.full_name !== inputs.repository')
    expect(verifier).toContain('MAX_RUN_METADATA_BYTES = 1024 * 1024')
    expect(verifier).toContain('parseStrictJson(source)')
    expect(verifier).toContain('constants.O_NOFOLLOW')
  })

  test('runner is local-only and reuses the atomic apply boundary', async () => {
    const runner = await source(runnerUrl)
    expect(runner).not.toMatch(/from\s+['"](?:node:)?child_process['"]|import\(\s*['"](?:node:)?child_process['"]\s*\)|require\(\s*['"](?:node:)?child_process['"]\s*\)/)
    expect(runner).not.toMatch(/node:https|node:http|undici|\bfetch\s*\(/)
    expect(runner).toContain('buildInstanceBundleApply')
    expect(runner).toContain('writeInstanceBundleApply')
    expect(runner).toContain('readCurrentInstanceManifest')
    expect(runner).toContain('parseInstanceBundleApplyArguments')
    expect(runner).toContain("'--expect-hash'")
    expect(runner).toContain("'--expect-artifact-hash'")
    expect(runner).toContain('Post-write manifest verification failed')
  })

  test('runner binds the run, hashes, required report fields and exact evidence set before writing', async () => {
    const runner = await source(runnerUrl)
    expect(runner).toContain('artifact_name review run ID must match review_run_id')
    expect(runner).toContain('instance-bundle-review-<instance-id>-<run-id>-<attempt>')
    expect(runner).toContain("['bundle.json', 'freshness.json', 'verification.json']")
    expect(runner).toContain('must contain exactly')
    expect(runner).toContain('MAX_REPORT_BYTES = 1024 * 1024')
    expect(runner).toContain('verification.json was not pinned to the trusted bundle hash')
    expect(runner).toContain('freshness.json did not verify the reviewed baseline state')
    expect(runner).toContain('apply plan target hash differs from review freshness evidence')
    expect(runner).toContain("open(path, 'wx', 0o600)")
  })

  test('documentation keeps run identity, repository apply, PR creation, CI and deployment distinct', async () => {
    const documentation = await source(documentationUrl)
    expect(documentation).toContain('workflow_dispatch')
    expect(documentation).toContain('review_run_id')
    expect(documentation).toContain('expected_bundle_hash')
    expect(documentation).toContain('expected_artifact_hash')
    expect(documentation).toContain('.github/workflows/review-instance-bundle.yml')
    expect(documentation).toContain('run attempt')
    expect(documentation).toContain('GitHub Actions API')
    expect(documentation).toContain('exactly one manifest')
    expect(documentation).toContain('Draft PR')
    expect(documentation).toContain('does not compile')
    expect(documentation).toContain('does not deploy')
    expect(documentation).toContain('does not claim that PR CI passed')
    expect(documentation).toContain('GITHUB_TOKEN')
    expect(documentation).toContain('CI workflow')
  })
})
